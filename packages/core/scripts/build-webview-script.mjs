// Bundles src/extract/webview-entry.ts into a self-contained script and writes it out as a
// string constant for the mobile app to inject into its WebView. Injected scripts can't
// import modules, so generating it keeps a single implementation of lot-page extraction.
//
// CI regenerates this file and fails if the committed copy is stale.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const entry = fileURLToPath(new URL("../src/extract/webview-entry.ts", import.meta.url));
const output = fileURLToPath(
  new URL("../src/extract/webview-script.generated.ts", import.meta.url),
);

const { outputFiles } = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  target: "es2017",
  charset: "utf8",
  legalComments: "none",
  write: false,
});

// react-native-webview expects injected scripts to end with a truthy expression.
const script = `${outputFiles[0].text}true;`;

await writeFile(
  output,
  [
    "// AUTO-GENERATED by scripts/build-webview-script.mjs from ./webview-entry.ts. Do not edit.",
    "// Regenerate with: npm run build:webview-script",
    "",
    `export const EXTRACT_LOT_DATA_SCRIPT = ${JSON.stringify(script)};`,
    "",
  ].join("\n"),
);
console.log(`Wrote ${output} (${script.length} chars)`);
